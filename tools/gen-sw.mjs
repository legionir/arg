#!/usr/bin/env node
// Builds sw.js — the offline service worker — from the files actually shipped to players.
//   node tools/gen-sw.mjs          # rewrite sw.js
//   node tools/gen-sw.mjs --check  # exit 1 if sw.js is stale (CI)
// Precache = index.html, VERSION, manifest, styles/, data/, game/ (without tests), fonts,
// portraits and UI assets. Strategy: network first, cache fallback, so an online player always
// gets fresh code and an offline player gets the last version that loaded completely.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const walk = (dir) => fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true }).flatMap((e) =>
  e.isDirectory() ? walk(dir + "/" + e.name) : [dir + "/" + e.name]);
const keep = (f) => !f.startsWith("game/tests") && f !== "game/tests.js" && !f.endsWith(".md") && !f.endsWith(".txt") &&
  !/^assets\/(units|terrain|environment|resources)\//.test(f) && !f.endsWith("manifest.json") && !f.includes("svg.html");
const files = ["index.html", "VERSION", "manifest.webmanifest",
  ...["styles", "data", "game", "assets"].flatMap(walk).filter(keep)].sort();
const hash = crypto.createHash("sha256");
for (const f of files) { hash.update(f); hash.update(fs.readFileSync(path.join(ROOT, f))); }
const version = fs.readFileSync(path.join(ROOT, "VERSION"), "utf8").trim().replace(/"/g, "");
const tag = version + "-" + hash.digest("hex").slice(0, 10);

const out = `// GENERATED by tools/gen-sw.mjs — do not edit by hand.
const CACHE = "arg-${tag}";
const FILES = ${JSON.stringify(["./", ...files], null, 0)};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("arg-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || url.pathname.endsWith("/sock")) return;
  e.respondWith(
    fetch(req).then((res) => {
      if (res && res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {}); }
      return res;
    }).catch(() => caches.match(req, { ignoreSearch: true }).then((hit) => hit || (req.mode === "navigate" ? caches.match("./") : Response.error())))
  );
});
`;
const target = path.join(ROOT, "sw.js");
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (cur !== out) { console.error("[gen-sw] sw.js is stale — run: node tools/gen-sw.mjs"); process.exit(1); }
  console.log(`[gen-sw] up to date (${files.length} files, ${tag})`);
} else {
  fs.writeFileSync(target, out);
  console.log(`[gen-sw] wrote sw.js (${files.length} files, ${tag})`);
}
